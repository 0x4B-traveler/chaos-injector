// Package experiment owns the inject -> observe window -> auto-rollback
// lifecycle (恢复监控层). Rollback is guaranteed through three redundant
// paths, mirroring the industrial platform's safety design:
//
//  1. a time.AfterFunc timer for auto-recovery after the duration;
//  2. calling Recover explicitly (CLI defer / error paths);
//  3. Recover is idempotent, so redundant calls are always safe.
//
// Every state transition is recorded on a timeline that can be persisted
// as JSON evidence for later analysis.
package experiment

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sync"
	"time"

	"chaos-injector/internal/fault"
)

// Event is one timeline entry.
type Event struct {
	At     time.Time `json:"at"`
	Phase  string    `json:"phase"`
	Detail string    `json:"detail"`
}

// Experiment runs one fault injection with guaranteed rollback.
type Experiment struct {
	Name     string
	Fault    fault.Fault
	Duration time.Duration

	// Seed is the PRNG seed of the random-decision layer, when the
	// experiment was generated by "random"; SeedSet marks it as recorded.
	Seed    int64
	SeedSet bool

	// Snapshots capture system state before injection and after rollback
	// as reproducibility evidence.
	Snapshots snapshotPair

	// OnEvent, when set, receives every timeline event as it is recorded.
	OnEvent func(Event)

	mu        sync.Mutex
	timeline  []Event
	timer     *time.Timer
	recovered bool
}

// snapshotPair carries the before/after system state snapshots.
type snapshotPair struct {
	Before fault.Snapshot `json:"before"`
	After  fault.Snapshot `json:"after"`
}

// Start checks preconditions, injects the fault, and arms auto-recovery.
func (e *Experiment) Start() error {
	e.Snapshots.Before = fault.Capture()
	e.record("start", fmt.Sprintf("fault=%s duration=%s", e.Fault.Describe(), e.Duration))
	if err := e.Fault.Check(); err != nil {
		e.record("error", err.Error())
		return err
	}
	e.record("check", "preconditions ok")
	if err := e.Fault.Inject(); err != nil {
		e.record("error", err.Error())
		return err
	}
	e.record("inject", fmt.Sprintf("fault=%s active", e.Fault.Name()))
	e.timer = time.AfterFunc(e.Duration, e.autoRecover)
	e.record("armed", fmt.Sprintf("auto-recovery in %s", e.Duration))
	return nil
}

// Recover rolls the fault back. Idempotent and safe to call any number of
// times, including before Start or after the timer already fired.
func (e *Experiment) Recover() {
	e.mu.Lock()
	if e.recovered {
		e.mu.Unlock()
		return
	}
	e.recovered = true
	timer := e.timer
	e.mu.Unlock()

	if timer != nil {
		timer.Stop()
	}
	_ = e.Fault.Recover()
	e.Snapshots.After = fault.Capture()
	e.record("recover", fmt.Sprintf("fault=%s rolled back", e.Fault.Name()))
}

func (e *Experiment) autoRecover() {
	e.Recover()
	e.record("auto", "auto-recovery fired by timer")
}

// Run blocks until the auto-recovery timer fires, then confirms rollback.
func (e *Experiment) Run() error {
	if err := e.Start(); err != nil {
		return err
	}
	deadline := time.Now().Add(e.Duration + 2*time.Second) // safety bound
	for {
		e.mu.Lock()
		// Both "recover" and "auto" must be on the timeline before Run
		// returns; autoRecover's goroutine records them after Recover().
		done := e.recovered && containsPhase(e.timeline, "recover") && containsPhase(e.timeline, "auto")
		e.mu.Unlock()
		if done || time.Now().After(deadline) {
			break
		}
		time.Sleep(10 * time.Millisecond)
	}
	e.Recover()
	e.record("done", "experiment finished")
	return nil
}

// Timeline returns a copy of the recorded events.
func (e *Experiment) Timeline() []Event {
	e.mu.Lock()
	defer e.mu.Unlock()
	out := make([]Event, len(e.timeline))
	copy(out, e.timeline)
	return out
}

// WriteTimeline persists the timeline as JSON evidence, creating parent
// directories as needed.
func (e *Experiment) WriteTimeline(path string) error {
	payload := struct {
		Experiment string       `json:"experiment"`
		Fault      string       `json:"fault"`
		Duration   string       `json:"duration"`
		Recovered  bool         `json:"recovered"`
		Seed       *int64       `json:"seed,omitempty"`
		Snapshot   snapshotPair `json:"snapshot"`
		Events     []Event      `json:"events"`
	}{
		Experiment: e.Name,
		Fault:      e.Fault.Describe(),
		Duration:   e.Duration.String(),
		Recovered:  e.recovered,
		Seed:       seedPtr(e.Seed, e.SeedSet),
		Snapshot:   e.Snapshots,
		Events:     e.Timeline(),
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	data, err := json.MarshalIndent(payload, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(data, '\n'), 0o644)
}

func (e *Experiment) record(phase, detail string) {
	ev := Event{At: time.Now().UTC(), Phase: phase, Detail: detail}
	e.mu.Lock()
	e.timeline = append(e.timeline, ev)
	e.mu.Unlock()
	if e.OnEvent != nil {
		e.OnEvent(ev)
	}
}

// containsPhase reports whether phase appears in timeline; the caller must
// hold e.mu.
func containsPhase(timeline []Event, phase string) bool {
	for _, ev := range timeline {
		if ev.Phase == phase {
			return true
		}
	}
	return false
}

// seedPtr returns a pointer for JSON output, nil when the seed is unset.
func seedPtr(v int64, set bool) *int64 {
	if !set {
		return nil
	}
	return &v
}
